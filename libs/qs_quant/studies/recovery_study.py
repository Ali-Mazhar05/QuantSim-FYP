"""K5 parameter-recovery study (Lane C guide §7.5): 50 replications per model.

Run from libs/qs_quant (about 7 minutes, most of it Merton):

    uv run python -m studies.recovery_study

It writes docs/report/k5-recovery.md, the report evidence for C-FR-01..03. The CI test
(tests/calibration/test_recovery.py) runs the same seeded streams: all 50 for GBM and OU,
the first 10 for Merton.
"""

import platform
import time
from datetime import UTC, datetime
from pathlib import Path

import numpy as np
import scipy
import statsmodels
from tests.calibration import simulate as sim
from tests.calibration.recovery import N_GBM_OU, N_MERTON, recover, table

import qs_quant

REPLICATIONS = 50
OUT = Path(__file__).resolve().parents[3] / "docs" / "report" / "k5-recovery.md"


def main() -> None:
    rows = []
    seconds: dict[str, float] = {}
    for model in ("gbm", "ou", "merton"):
        start = time.perf_counter()
        rows += recover(model, REPLICATIONS)
        seconds[model] = time.perf_counter() - start
    passed = all(row.passes for row in rows)
    text = f"""# K5 calibration: parameter-recovery study

Generated by `libs/qs_quant/studies/recovery_study.py` on
{datetime.now(UTC):%d %b %Y %H:%M} UTC with qs_quant {qs_quant.__version__}, NumPy
{np.__version__}, SciPy {scipy.__version__}, statsmodels {statsmodels.__version__}, Python
{platform.python_version()} ({platform.system()}).

**Method (Lane C guide §7.5).** For each model, {REPLICATIONS} independent samples are
simulated with known parameters by exact reference simulators (the same formulas as Lane
B's path generators), fitted, and summarised per parameter:

- *coverage*: share of replications whose true value lies within estimate +- 2 SE; pass
  at 85% or more (80% for Merton's lam and sigma_j);
- *standardised bias*: mean(estimate - true) / mean(SE); pass when below 1 in absolute
  value.

Sample sizes: GBM and OU n = {N_GBM_OU:,} daily observations (10 years), Merton
n = {N_MERTON:,}. Time step 1/252. True values: GBM {sim.GBM_TRUE}; OU kappa = 5,
theta = ln 100, sigma = 0.3; Merton {sim.MERTON_TRUE}.

**Result: {"all parameters pass" if passed else "SOME PARAMETERS FAIL"}.**

{table(rows, REPLICATIONS)}

Run time: GBM {seconds["gbm"]:.1f} s, OU {seconds["ou"]:.1f} s, Merton {seconds["merton"]:.1f} s.

**Reading the numbers.** The OU mean-reversion speed kappa is biased upward in finite
samples, a known property of its maximum-likelihood estimator (Tang and Chen 2009,
"Parameter estimation and bias correction for diffusion processes", J. Econometrics
149); here the bias is well inside one standard error, so the reported SE stays honest.
The Merton drift mu is weakly identified over 20 years, which shows as a large SE rather
than as bias. Coverage above 95% for some parameters means their SEs are slightly
conservative.
"""
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(text)


if __name__ == "__main__":
    main()
