import { AlertTriangle, ArrowRight, Eye, Search, X } from 'lucide-react'
import { useNavigate } from 'react-router-dom'
import Button from '../../components/forms/Button'
import Panel from '../../components/layout/Panel'
import PageHeader from '../../components/layout/PageHeader'
import EmptyState from '../../components/status/EmptyState'
import RiskBadge from '../../components/status/RiskBadge'
import StatusPill from '../../components/status/StatusPill'
import { useDemoStore } from '../../demo/demoState'
import { useNotifications } from '../../demo/notifications'
import { useRiskAlerts } from '../../demo/useRiskAlerts'
import { ALERT_HISTORY } from '../../services/mock/alerts'

export default function AlertsPage() {
  const navigate = useNavigate()
  const dismissAlert = useDemoStore((s) => s.dismissAlert)
  const push = useNotifications((s) => s.push)
  const { alerts, active } = useRiskAlerts()

  return (
    <div className="qs-fade-in flex flex-col gap-6">
      <PageHeader
        title="Alert Hub"
        description="Risk alerts generated by the lenses you ran."
        action={
          active.length > 0 && (
            <StatusPill tone="danger" dot>
              {active.length} active
            </StatusPill>
          )
        }
      />

      {active.length > 0 ? (
        <div className="flex flex-col gap-4">
          {active.map((a) => (
            <div key={a.id} className="qs-panel overflow-hidden rounded border-l-4 border-l-[var(--color-risk-high)]">
              <div className="flex items-start gap-4 p-5">
                <AlertTriangle size={22} className="mt-0.5 shrink-0 text-[var(--color-risk-high)]" />
                <div className="flex-1">
                  <div className="flex items-center gap-2">
                    <span className="text-sm font-bold uppercase tracking-wide text-[var(--color-risk-high)]">
                      {a.title}
                    </span>
                    <RiskBadge level={a.severity} size="sm" />
                  </div>
                  <div className="mt-1 text-base font-semibold text-[var(--color-text-primary)]">{a.message}</div>
                  <div className="mono mt-1 text-sm text-[var(--color-text-secondary)]">{a.detail}</div>
                  <div className="mt-3 flex flex-wrap gap-x-6 gap-y-1 text-xs text-[var(--color-text-muted)]">
                    <span>
                      Portfolio: <span className="text-[var(--color-text-secondary)]">Momentum Strategy</span>
                    </span>
                    <span>
                      Source: <span className="text-[var(--color-text-secondary)]">{a.source}</span>
                    </span>
                    <span>
                      Created: <span className="mono text-[var(--color-text-secondary)]">{a.createdAt}</span>
                    </span>
                  </div>
                  <div className="mt-4 flex flex-wrap gap-2">
                    <Button
                      size="sm"
                      icon={Search}
                      onClick={() => navigate(a.investigateRoute ?? '/risk/overview')}
                    >
                      Investigate
                    </Button>
                    <Button size="sm" variant="secondary" icon={Eye} onClick={() => navigate('/risk/composite')}>
                      View Analysis
                    </Button>
                    <Button
                      size="sm"
                      variant="ghost"
                      icon={X}
                      onClick={() => {
                        dismissAlert(a.id)
                        push('Alert dismissed', 'info')
                      }}
                    >
                      Dismiss
                    </Button>
                  </div>
                </div>
              </div>
            </div>
          ))}
        </div>
      ) : (
        <EmptyState
          icon={AlertTriangle}
          title={alerts.length > 0 ? 'All alerts dismissed' : 'No alerts yet'}
          description={
            alerts.length > 0
              ? 'Every alert from this run has been dismissed. It stays in the history below.'
              : 'Alerts are raised once your risk analysis reaches the risk hub.'
          }
          action={
            <Button size="sm" icon={ArrowRight} onClick={() => navigate('/risk/overview')}>
              Go to Risk Analysis
            </Button>
          }
        />
      )}

      <Panel title="Alert History" bodyClassName="p-0">
        <div className="divide-y divide-[var(--color-border)]">
          {[
            ...alerts.map((a) => ({
              title: a.message,
              severity: a.severity,
              time: a.createdAt,
              status: a.status,
            })),
            ...ALERT_HISTORY.map((h) => ({ ...h, status: 'Dismissed' as const })),
          ].map((a, i) => (
            <div key={i} className="flex items-center justify-between gap-4 px-4 py-3">
              <div className="flex items-center gap-3">
                <RiskBadge level={a.severity} size="sm" />
                <span className="text-sm text-[var(--color-text-secondary)]">{a.title}</span>
              </div>
              <div className="flex items-center gap-3">
                <span className="mono text-xs text-[var(--color-text-muted)]">{a.time}</span>
                <StatusPill tone={a.status === 'Active' ? 'danger' : 'neutral'}>{a.status}</StatusPill>
              </div>
            </div>
          ))}
        </div>
      </Panel>
    </div>
  )
}
