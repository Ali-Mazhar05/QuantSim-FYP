#!/usr/bin/env bash
# Builds Jenkins' login configuration for laptop hosts from secrets/team_users, so every
# team member has their own account on whichever laptop hosts Jenkins. Called by
# init-env.sh; writes ci/jenkins/.state/security-local.yaml (never committed) and prints
# the comma-separated list of approvers.
#
# secrets/team_users, one line per person:
#     username:password:role
#   role is one of
#     admin      full control of Jenkins
#     approver   build, cancel and replay jobs, and approve ACC and PROD
#     developer  build, cancel and replay jobs
#   Usernames are lowercase letters, digits, dots, dashes and underscores. Lines starting
#   with # are ignored. The built-in "admin" account (secrets/admin_password) always
#   exists as a break-glass login.
set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
users_file="$here/secrets/team_users"
out_dir="$here/.state"
out="$out_dir/security-local.yaml"

mkdir -p "$out_dir"

# YAML single-quoted scalar, with JCasC's ${...} interpolation escaped
quote() {
  local value=${1//\'/\'\'}
  value=${value//\$\{/^\$\{}
  printf "'%s'" "$value"
}

admins=("admin")
approvers=("admin")
builders=()
users_yaml=""

if [[ -f "$users_file" ]]; then
  line_no=0
  while IFS= read -r line || [[ -n "$line" ]]; do
    line_no=$((line_no + 1))
    line="${line%$'\r'}"
    [[ -z "$line" || "$line" == \#* ]] && continue
    username="${line%%:*}"
    rest="${line#*:}"
    role="${rest##*:}"
    password="${rest%:*}"
    if [[ ! "$username" =~ ^[a-z0-9._-]+$ || "$username" == "admin" ]]; then
      echo "team_users line $line_no: invalid username '$username'" >&2; exit 1
    fi
    if [[ "$rest" != *:* || ${#password} -lt 12 ]]; then
      echo "team_users line $line_no: password must be at least 12 characters" >&2; exit 1
    fi
    case "$role" in
      admin)     admins+=("$username"); approvers+=("$username") ;;
      approver)  builders+=("$username"); approvers+=("$username") ;;
      developer) builders+=("$username") ;;
      *) echo "team_users line $line_no: role must be admin, approver or developer" >&2; exit 1 ;;
    esac
    users_yaml+="        - id: $(quote "$username")"$'\n'
    users_yaml+="          password: $(quote "$password")"$'\n'
  done < "$users_file"
fi

entries() {
  local name
  for name in "$@"; do
    printf '              - user: %s\n' "$(quote "$name")"
  done
}

umask 077
{
  echo "# Generated by ci/jenkins/team-accounts.sh from secrets/team_users. Do not edit."
  echo "jenkins:"
  echo "  securityRealm:"
  echo "    local:"
  echo "      allowsSignup: false"
  echo "      users:"
  echo "        - id: 'admin'"
  echo "          name: 'QuantSim Admin'"
  echo "          password: \"\${admin_password}\""
  printf '%s' "$users_yaml"
  echo "  authorizationStrategy:"
  echo "    roleBased:"
  echo "      roles:"
  echo "        global:"
  echo "          - name: 'admin'"
  echo "            description: 'Full control'"
  echo "            permissions:"
  echo "              - 'Overall/Administer'"
  echo "            entries:"
  entries "${admins[@]}"
  if (( ${#builders[@]} )); then
    echo "          - name: 'developer'"
    echo "            description: 'Team members: view, build, cancel and replay jobs'"
    echo "            permissions:"
    for permission in Overall/Read Job/Read Job/Build Job/Cancel Job/Workspace Run/Replay View/Read; do
      echo "              - '$permission'"
    done
    echo "            entries:"
    entries "${builders[@]}"
  fi
} > "$out"

(IFS=,; echo "${approvers[*]}")
